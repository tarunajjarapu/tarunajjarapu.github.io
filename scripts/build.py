#!/usr/bin/env python3
"""Render the GitHub Pages site. Published HTML is committed alongside its source."""

import argparse
from datetime import date, datetime, time, timezone
from email.utils import format_datetime
from html import escape
import json
from pathlib import Path
import re
import shutil
from string import Template
import xml.etree.ElementTree as ET

import markdown

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "site"
CATEGORIES = {"Systems", "ML", "Notes"}
GENERATED = "<!-- Generated by scripts/build.py. Edit files in site/ instead. -->\n"


def load_posts(today):
    posts = []
    slugs = set()
    for path in sorted((SOURCE / "posts").glob("*.md")):
        text = path.read_text(encoding="utf-8")
        match = re.match(r"\A---\n(.*?)\n---\n(.*)\Z", text, re.S)
        if not match:
            raise ValueError(f"{path.name}: expected metadata between --- lines")
        metadata = {}
        for line in match[1].splitlines():
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            key, separator, value = line.partition(":")
            if not separator:
                raise ValueError(f"{path.name}: invalid metadata line {line!r}")
            value = value.strip()
            if len(value) >= 2 and value[0] == value[-1] and value[0] in {'"', "'"}:
                value = value[1:-1]
            metadata[key.strip()] = value
        draft = metadata.get("draft", "true").lower()
        if draft not in {"true", "false"}:
            raise ValueError(f"{path.name}: draft must be true or false")
        if draft == "true":
            continue
        for field in ("title", "description", "date", "category", "slug"):
            if not metadata.get(field):
                raise ValueError(f"{path.name}: missing {field}")
        published = date.fromisoformat(metadata["date"])
        if published > today:
            continue
        slug = metadata["slug"]
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", slug):
            raise ValueError(f"{path.name}: slug must use lowercase words separated by hyphens")
        if slug in slugs:
            raise ValueError(f"Duplicate post slug: {slug}")
        slugs.add(slug)
        if metadata["category"] not in CATEGORIES:
            raise ValueError(f"{path.name}: category must be Systems, ML, or Notes")
        body = markdown.markdown(match[2], extensions=["fenced_code", "tables", "sane_lists", "toc"])
        words = re.findall(r"\b\w+\b", re.sub(r"<[^>]+>", " ", body))
        posts.append({**metadata, "published": published, "body": body,
                      "reading_time": str(max(1, (len(words) + 219) // 220)),
                      "path": f"/writing/{slug}/"})
    return sorted(posts, key=lambda post: (post["published"], post["slug"]), reverse=True)


def load_videos(today):
    entries = json.loads((SOURCE / "videos.json").read_text())
    if not isinstance(entries, list):
        raise ValueError("videos.json must contain a list")
    videos = []
    ids = set()
    for entry in entries:
        if not isinstance(entry, dict) or not isinstance(entry.get("draft", True), bool):
            raise ValueError("Each video must be an object with a boolean draft field")
        if entry.get("draft", True):
            continue
        for field in ("title", "description", "date", "category", "youtube_id"):
            if not isinstance(entry.get(field), str) or not entry[field].strip():
                raise ValueError(f"Video is missing {field}")
        published = date.fromisoformat(entry["date"])
        if published > today:
            continue
        video_id = entry["youtube_id"]
        if not re.fullmatch(r"[A-Za-z0-9_-]{11}", video_id):
            raise ValueError("youtube_id must be the 11-character ID from a YouTube video URL")
        if video_id in ids:
            raise ValueError(f"Duplicate YouTube video: {video_id}")
        if entry["category"] not in CATEGORIES:
            raise ValueError("Video category must be Systems, ML, or Notes")
        ids.add(video_id)
        videos.append({**entry, "published": published})
    return sorted(videos, key=lambda video: (video["published"], video["youtube_id"]), reverse=True)


def build(output, today):
    config = json.loads((SOURCE / "config.json").read_text())
    posts = load_posts(today)
    videos = load_videos(today)
    output.mkdir(parents=True, exist_ok=True)
    site_url = config["url"].rstrip("/")
    common = {key: escape(str(value), quote=True) for key, value in config.items()}
    common.update(site_url=site_url, year=str(today.year))
    base = Template((SOURCE / "templates/base.html").read_text())
    pages = []

    def render(template, context):
        return Template((SOURCE / "templates" / template).read_text()).substitute({**common, **context})

    def page(path, title, description, content, active, og_type="website"):
        navigation = "".join(
            f'<a href="{href}"' + (' aria-current="page"' if active == label else '') + f'>{label}</a>'
            for label, href in [("Home", "/"), ("Writing", "/writing/"), ("Videos", "/videos/"), ("About", "/about/")]
        )
        html = base.substitute({**common, "title": escape(title), "description": escape(description, quote=True),
                                "canonical": escape(site_url + path, quote=True), "og_type": og_type,
                                "navigation": navigation, "content": content,
                                "terminal_dock": render("terminal.html", {})})
        destination = output / (path.lstrip("/") + "index.html" if path.endswith("/") else path.lstrip("/"))
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(GENERATED + html, encoding="utf-8")
        pages.append(path)

    youtube = config.get("youtube", "").strip()
    if youtube and not re.fullmatch(r"https://(?:www\.)?youtube\.com/[^\s\"<>]+", youtube):
        raise ValueError("youtube must be an https://www.youtube.com/ channel URL")
    common["youtube_footer"] = f'<a href="{escape(youtube, quote=True)}" target="_blank" rel="noopener noreferrer">YouTube ↗</a>' if youtube else ""

    # Remove only generated article pages, so a removed or unpublished post disappears.
    # Validate post data and configuration before touching the previous build.
    for old in (output / "writing").glob("*/index.html"):
        if old.read_text(encoding="utf-8").startswith(GENERATED):
            old.unlink()
            if not any(old.parent.iterdir()):
                old.parent.rmdir()

    home_context = {
        "featured_href": "/writing/",
        "featured_label": "TECHNICAL NOTES",
        "featured_meta": "COMING SOON",
        "featured_title": "ML systems.<br>Implementation notes.",
        "featured_footer": "No published notes yet.",
        "youtube_home_status": "FIND ME ON YOUTUBE" if youtube or videos else "COMING SOON TO YOUTUBE",
    }
    if posts:
        latest = posts[0]
        home_context.update(featured_href=latest["path"], featured_label=f'LATEST / {latest["category"].upper()}',
                            featured_meta=f'{latest["reading_time"]} MIN READ', featured_title=escape(latest["title"]),
                            featured_footer="Read the latest note.")
    page("/", "Tarun Ajjarapu — ML Systems & Infrastructure", config["description"], render("home.html", home_context), "Home")

    cards = "".join(
        f'<a class="post-row" href="{post["path"]}" data-category="{post["category"]}"><div>'
        f'<span class="eyebrow muted">{post["category"].upper()} · {post["published"].strftime("%b %d, %Y")} · {post["reading_time"]} MIN READ</span>'
        f'<h2>{escape(post["title"])}</h2><p>{escape(post["description"])}</p></div><span class="row-arrow" aria-hidden="true">↗</span></a>'
        for post in posts
    )
    page("/writing/", "Writing — Tarun Ajjarapu", "Technical notes on operating systems, distributed infrastructure, and machine learning.",
         render("writing.html", {"posts": cards, "post_count": str(len(posts)), "empty_hidden": "hidden" if posts else ""}), "Writing")
    video_cards = "".join(
        f'<a class="published-video" href="https://www.youtube.com/watch?v={video["youtube_id"]}" target="_blank" rel="noopener noreferrer">'
        f'<span class="episode-number" aria-hidden="true">{number:02d}</span><div><span class="eyebrow muted">{video["category"]} · {video["published"].strftime("%b %d, %Y")}</span>'
        f'<h3>{escape(video["title"])}</h3><p>{escape(video["description"])}</p></div><span class="episode-watch">Watch on YouTube ↗</span></a>'
        for number, video in enumerate(videos, start=1)
    )
    video_context = {
        "video_status": "ON YOUTUBE" if youtube or videos else "CHANNEL COMING SOON",
        "video_message": "Published technical breakdowns." if videos else ("The channel is live. The first video is in progress." if youtube else "The channel hasn’t launched yet. Planned topics are listed below."),
        "video_link": f'<a class="button" href="{escape(youtube, quote=True)}" target="_blank" rel="noopener noreferrer">Visit the channel <span aria-hidden="true">↗</span></a>' if youtube else ('<a class="button" href="#episodes">Watch the videos <span aria-hidden="true">↓</span></a>' if videos else '<a class="button" href="#rabbit-holes">View planned topics <span aria-hidden="true">↓</span></a>'),
        "published_videos": '<section class="published-videos wrap" id="episodes" aria-labelledby="episodes-title"><div class="section-heading"><div><p class="eyebrow muted">PUBLISHED</p><h2 id="episodes-title">Videos.</h2></div></div>' + video_cards + '</section>' if videos else "",
    }
    page("/videos/", f'{config["channel_name"]} — Videos', config["channel_tagline"] + " Videos on operating systems, low-level code, and machine learning by Tarun Ajjarapu.", render("videos.html", video_context), "Videos")
    page("/about/", "About — Tarun Ajjarapu", "Member of Technical Staff at Judgment Labs, working on infrastructure and agents. Previously Databricks and Stripe.", render("about.html", {}), "About")
    for post in posts:
        article = render("article.html", {
            "category": post["category"].upper(), "date": post["published"].strftime("%B %d, %Y"),
            "reading_time": post["reading_time"], "post_title": escape(post["title"]),
            "post_description": escape(post["description"]), "body": post["body"]
        })
        page(post["path"], f'{post["title"]} — Tarun Ajjarapu', post["description"], article, "Writing", "article")
    page("/404.html", "Page not found — Tarun Ajjarapu", "This page does not exist. Navigate using the site terminal.", render("404.html", {}), "")

    rss = ET.Element("rss", version="2.0")
    channel = ET.SubElement(rss, "channel")
    for key, value in {"title": "Tarun’s notebook", "link": site_url + "/writing/", "description": config["description"], "language": "en-us"}.items():
        ET.SubElement(channel, key).text = value
    for post in posts:
        item = ET.SubElement(channel, "item")
        for key, value in {"title": post["title"], "link": site_url + post["path"], "guid": site_url + post["path"], "description": post["description"], "category": post["category"], "pubDate": format_datetime(datetime.combine(post["published"], time.min, timezone.utc), usegmt=True)}.items():
            ET.SubElement(item, key).text = value
    ET.indent(rss)
    ET.ElementTree(rss).write(output / "feed.xml", encoding="utf-8", xml_declaration=True)
    sitemap = ET.Element("urlset", xmlns="http://www.sitemaps.org/schemas/sitemap/0.9")
    for path in pages:
        if path != "/404.html":
            ET.SubElement(ET.SubElement(sitemap, "url"), "loc").text = site_url + path
    ET.indent(sitemap)
    ET.ElementTree(sitemap).write(output / "sitemap.xml", encoding="utf-8", xml_declaration=True)
    (output / "robots.txt").write_text(f"User-agent: *\nAllow: /\nSitemap: {site_url}/sitemap.xml\n")
    (output / ".nojekyll").touch()
    if output != ROOT:
        for directory in ("assets", "images"):
            shutil.copytree(ROOT / directory, output / directory, dirs_exist_ok=True)
    # Only published posts enter the terminal's searchable index.
    (output / "site-index.json").write_text(json.dumps({"posts": [
        {"title": post["title"], "description": post["description"], "path": post["path"],
         "slug": post["slug"], "category": post["category"]} for post in posts
    ]}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Built {len(pages)} pages, {len(posts)} published posts, and {len(videos)} published videos in {output}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT, help="Output folder (defaults to repository root)")
    args = parser.parse_args()
    build(args.output.resolve(), date.today())
